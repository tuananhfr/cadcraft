use std::fs;
use std::path::PathBuf;

use cadcraft_ui_egui::menus::UI_COMMANDS;

fn render_doc() -> String {
    let mut rows = UI_COMMANDS.to_vec();
    rows.sort_by_key(|row| row.0);
    let mut out = String::from(
        "# UI command ids\n\n\
         Generated by `UPDATE_UI_COMMAND_IDS=1 cargo test -p cadcraft-ui-egui --test ui_command_ids`; do not edit by hand.\n\n\
         | id | label | menu | shortcut |\n| --- | --- | --- | --- |\n",
    );
    for (id, label, menu, shortcut) in rows {
        let menu = if menu.is_empty() { String::from("—") } else { menu.join(" ▸ ") };
        out.push_str(&format!(
            "| `{}` | {} | {} | {} |\n",
            id.replace('|', "\\|"),
            label.replace('|', "\\|"),
            menu.replace('|', "\\|"),
            shortcut.unwrap_or("—").replace('|', "\\|")
        ));
    }
    out
}

#[test]
fn ui_command_ids_doc_is_current() -> Result<(), Box<dyn std::error::Error>> {
    let doc = render_doc();
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../docs/workspace/ui-command-ids.md");
    if std::env::var("UPDATE_UI_COMMAND_IDS").is_ok_and(|value| value == "1") {
        fs::write(&path, &doc)?;
        return Ok(());
    }
    let on_disk = fs::read_to_string(&path)?;
    assert_eq!(on_disk.replace("\r\n", "\n"), doc, "docs/workspace/ui-command-ids.md is stale; run with UPDATE_UI_COMMAND_IDS=1");
    Ok(())
}
