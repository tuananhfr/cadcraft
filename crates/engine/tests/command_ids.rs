//! Guards the stable command ids that workspaces, palettes and saved layouts refer to: ids may be
//! renamed (via `RENAMED`) but never silently disappear. `UPDATE_COMMAND_IDS=1` regenerates the
//! snapshot and the registry doc.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::PathBuf;

use cadcraft_engine::cmd::registry::{
    CommandMeta, EDIT_IDS, EXECUTE_IDS, FILE_IDS, LISP_IDS, RENAMED, RiskClass, XREF_IDS, capability_present, command_registry, resolve_stable,
};

fn manifest_path(rel: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(rel)
}

fn updating() -> bool {
    // Opt-in so a normal run can never rewrite the guarded files.
    std::env::var("UPDATE_COMMAND_IDS").is_ok_and(|v| v == "1")
}

fn risk_name(r: RiskClass) -> &'static str {
    match r {
        RiskClass::Read => "read",
        RiskClass::Edit => "edit",
        RiskClass::File => "file",
        RiskClass::Execute => "execute",
    }
}

fn render_doc(reg: &[CommandMeta]) -> String {
    let mut rows: Vec<&CommandMeta> = reg.iter().collect();
    rows.sort_by_key(|m| m.stable_id);
    let mut out = String::from(
        "# Command ids\n\n\
         Generated by `UPDATE_COMMAND_IDS=1 cargo test -p cadcraft-engine --test command_ids`; do not edit by hand.\n\
         Engine commands only; UI-only ids are added by `ui-egui`. An id listed here never disappears: it is renamed through `RENAMED` or it stays.\n\n\
         | stable_id | category | risk | aliases |\n| --- | --- | --- | --- |\n",
    );
    for m in rows {
        out.push_str(&format!("| `{}` | {} | {} | {} |\n", m.stable_id, m.category, risk_name(m.risk_class), m.aliases.join(", ")));
    }
    out
}

fn by_id(reg: &[CommandMeta]) -> BTreeMap<&'static str, &CommandMeta> {
    reg.iter().map(|m| (m.stable_id, m)).collect()
}

#[test]
fn ids_are_unique_and_aliases_do_not_collide() {
    let reg = command_registry();
    let mut ids = BTreeSet::new();
    for m in &reg {
        assert!(ids.insert(m.stable_id), "duplicate stable id `{}`", m.stable_id);
    }
    let mut owner: BTreeMap<String, &str> = BTreeMap::new();
    for m in &reg {
        for a in &m.aliases {
            let a = a.to_ascii_lowercase();
            if let Some(other) = ids.get(a.as_str()) {
                assert_eq!(*other, m.stable_id, "alias `{a}` of `{}` is the id of another command", m.stable_id);
            }
            if let Some(prev) = owner.insert(a.clone(), m.stable_id) {
                assert_eq!(prev, m.stable_id, "alias `{a}` is used by `{prev}` and `{}`", m.stable_id);
            }
        }
    }
}

#[test]
fn stable_ids_never_disappear() {
    let reg = command_registry();
    let current: BTreeSet<&str> = reg.iter().map(|m| m.stable_id).collect();
    let path = manifest_path("tests/data/command_ids.txt");
    let recorded: BTreeSet<String> =
        fs::read_to_string(&path).map(|t| t.lines().map(str::trim).filter(|l| !l.is_empty()).map(String::from).collect()).unwrap_or_default();
    if updating() {
        let mut all: BTreeSet<String> = recorded.clone();
        all.extend(current.iter().map(|s| s.to_string()));
        let text: String = all.iter().map(|id| format!("{id}\n")).collect();
        fs::write(&path, text).expect("write command_ids.txt");
        return;
    }
    assert!(!recorded.is_empty(), "{} is missing or empty; run with UPDATE_COMMAND_IDS=1", path.display());
    let gone: Vec<&String> = recorded.iter().filter(|id| !current.contains(id.as_str()) && !RENAMED.iter().any(|(old, _)| old == id)).collect();
    assert!(gone.is_empty(), "command ids disappeared without a RENAMED entry: {gone:?}");
}

#[test]
fn renamed_entries_point_at_live_ids() {
    let ids: BTreeSet<&str> = command_registry().iter().map(|m| m.stable_id).collect();
    for (old, new) in RENAMED {
        assert!(ids.contains(new), "RENAMED `{old}` -> `{new}`: target is not a registry id");
    }
    assert_eq!(resolve_stable("line"), Some("line"));
    assert_eq!(resolve_stable("no.such.command"), None);
}

#[test]
fn appload_is_execute_and_line_is_edit() {
    let reg = command_registry();
    let map = by_id(&reg);
    let risk = |id: &str| map.get(id).unwrap_or_else(|| panic!("`{id}` missing from the registry")).risk_class;
    assert_eq!(risk("appload"), RiskClass::Execute);
    assert_eq!(risk("script"), RiskClass::Execute);
    assert_eq!(risk("line"), RiskClass::Edit);
    assert_eq!(risk("open"), RiskClass::File);
    assert_eq!(risk("plot"), RiskClass::File);
    assert_eq!(risk("bsave"), RiskClass::Edit);
    assert_eq!(risk("undo"), RiskClass::Edit);
    assert_eq!(risk("new"), RiskClass::File);
    assert_eq!(risk("close"), RiskClass::File);
    assert_eq!(risk("list"), RiskClass::Read);
    assert_eq!(risk("dist"), RiskClass::Read);
}

#[test]
fn permissions_follow_risk_and_category_has_a_fallback() {
    let reg = command_registry();
    let map = by_id(&reg);
    assert!(map["list"].permissions.is_empty());
    assert_eq!(map["line"].permissions, ["cad.edit"]);
    assert_eq!(map["open"].permissions, ["cad.file"]);
    assert_eq!(map["appload"].permissions, ["cad.execute"]);
    assert_eq!(map["line"].category, "Draw");
    assert!(reg.iter().all(|m| !m.category.is_empty()));
    assert_eq!(map["appload"].capabilities, ["lisp"]);
    assert_eq!(map["fonts"].capabilities, ["fonts"]);
    assert!(map["line"].capabilities.is_empty());
}

#[test]
fn listed_ids_exist_in_registry() {
    // Not engine commands yet; the lists keep them so the risk class is right once they land.
    const NOT_YET: &[&str] = &["load", "vbarun", "ubplot"];
    let ids: BTreeSet<&str> = command_registry().iter().map(|m| m.stable_id).collect();
    for (table, list) in
        [("EDIT_IDS", EDIT_IDS), ("FILE_IDS", FILE_IDS), ("EXECUTE_IDS", EXECUTE_IDS), ("LISP_IDS", LISP_IDS), ("XREF_IDS", XREF_IDS)]
    {
        for id in list {
            assert!(ids.contains(id) || NOT_YET.contains(id), "{table} lists `{id}`, which is not a registry command");
        }
    }
}

#[test]
fn capability_table() {
    assert!(!capability_present("sheetset"));
    assert!(capability_present("fonts"));
}

#[test]
fn registry_doc_is_current() {
    let doc = render_doc(&command_registry());
    let path = manifest_path("../../docs/workspace/command-ids.md");
    if updating() {
        fs::write(&path, &doc).expect("write command-ids.md");
        return;
    }
    let on_disk = fs::read_to_string(&path).unwrap_or_default();
    assert_eq!(on_disk.replace("\r\n", "\n"), doc, "docs/workspace/command-ids.md is stale; run with UPDATE_COMMAND_IDS=1");
}
