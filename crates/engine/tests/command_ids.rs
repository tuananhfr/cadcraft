        [("EDIT_IDS", EDIT_IDS), ("FILE_IDS", FILE_IDS), ("EXECUTE_IDS", EXECUTE_IDS), ("LISP_IDS", LISP_IDS), ("XREF_IDS", XREF_IDS)]
