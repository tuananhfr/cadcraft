#[test]
fn registry_doc_is_current() {
    let doc = render_doc(&command_registry());
    let path = manifest_path("../../docs/workspace/command-ids.md");
    if updating() {
        fs::write(&path, &doc).expect("write command-ids.md");
        return;
    }
    let on_disk = fs::read_to_string(&path).unwrap_or_default();
    let rows = |text: &str| -> BTreeMap<String, String> {
        text.lines()
            .enumerate()
            .map(|(index, line)| {
                let id =
                    line.strip_prefix("| `").and_then(|row| row.split('`').next()).map(String::from).unwrap_or_else(|| format!("header:{index}"));
                (id, line.to_string())
            })
            .collect()
    };
    let differences = snapshot_differences(&rows(&doc), &rows(&on_disk));
    assert!(differences.is_empty(), "docs/workspace/command-ids.md is stale; run with UPDATE_COMMAND_IDS=1:\n{}", differences.join("\n"));
    assert_eq!(on_disk.replace("\r\n", "\n"), doc, "registry doc rows must retain their generated order and formatting");
}

fn snapshot_differences(expected: &BTreeMap<String, String>, found: &BTreeMap<String, String>) -> Vec<String> {
    let ids: BTreeSet<&String> = expected.keys().chain(found.keys()).collect();
    ids.into_iter()
        .filter_map(|id| {
            let expected = expected.get(id).map(String::as_str);
            let found = found.get(id).map(String::as_str);
            if expected == found {
                None
            } else {
                Some(format!("id={id} expected={} found={}", expected.unwrap_or("<missing>"), found.unwrap_or("<missing>")))
            }
        })
        .collect()
}

#[test]
fn namespaced_ids_are_unique_and_stable() {
    let reg = command_registry();
    let mut namespaces = BTreeSet::new();
    let mut current = BTreeMap::new();
    for meta in &reg {
        assert!(namespaces.insert(meta.namespaced_id.to_ascii_lowercase()), "duplicate namespace `{}` for `{}`", meta.namespaced_id, meta.stable_id);
        current.insert(meta.stable_id.to_string(), meta.namespaced_id.clone());
    }
    let path = manifest_path("tests/data/namespaced_ids.txt");
    let text = fs::read_to_string(&path).unwrap_or_default();
    let mut recorded = BTreeMap::new();
    for line in text.lines().filter(|line| !line.is_empty()) {
        let (id, namespace) = line.split_once('\t').unwrap_or_else(|| panic!("invalid namespace snapshot row `{line}`"));
        assert!(recorded.insert(id.to_string(), namespace.to_string()).is_none(), "duplicate snapshot id `{id}`");
    }
    let differences = snapshot_differences(&recorded, &current);
    if updating() {
        let changed: BTreeMap<String, String> =
            current.iter().filter(|(id, _)| recorded.contains_key(*id)).map(|(id, ns)| (id.clone(), ns.clone())).collect();
        let conflicts = snapshot_differences(&recorded, &changed);
        assert!(conflicts.is_empty(), "existing namespaces cannot be rewritten; add NAMESPACE_PINS before moving menus:\n{}", conflicts.join("\n"));
        let text: String = current.iter().map(|(id, ns)| format!("{id}\t{ns}\n")).collect();
        fs::write(&path, text).expect("write namespaced_ids.txt");
    } else {
        assert!(differences.is_empty(), "namespace snapshot differs; run with UPDATE_COMMAND_IDS=1 for additions:\n{}", differences.join("\n"));
        assert!(!recorded.is_empty(), "namespace snapshot is empty");
    }
    for (id, namespace) in NAMESPACE_PINS {
        assert_eq!(current.get(*id).map(String::as_str), Some(*namespace), "pin `{id}`");
    }
    let line = find_command("line").expect("line spec");
    let ui = cadcraft_engine::cmd::CommandSpec::new("ui.test", "Test", line.run).menu(&["Draw"]);
    assert_eq!(namespaced_id(&ui), "ui.test");
    assert_eq!(namespaced_id(find_command("-block").expect("-block spec")), "cad.other.-block");
}

#[test]
fn resolve_command_accepts_both_forms() {
    assert_eq!(resolve_command("cad.draw.line"), Some("line"));
    assert_eq!(resolve_command("LINE"), Some("line"));
    assert_eq!(resolve_command("CAD.DRAW.LINE"), Some("line"));
    assert_eq!(resolve_command("l"), None);
    assert_eq!(resolve_command("cad.draw.nope"), None);
    assert_eq!(resolve_command("cad.modify.line"), None);
    assert_eq!(find_command("cad.draw.line").map(|c| c.id), Some("line"));
    for meta in command_registry() {
        assert_eq!(resolve_command(meta.stable_id), Some(meta.stable_id));
        assert_eq!(resolve_command(&meta.namespaced_id), Some(meta.stable_id));
    }
    for (old, new) in RENAMED {
        assert_eq!(resolve_command(old), Some(*new));
    }
}

#[test]
fn registry_contexts_status_version() {
    let reg = command_registry();
    let map = by_id(&reg);
    let meta = |id: &str| *map.get(id).unwrap_or_else(|| panic!("missing registry id `{id}`"));
    let line = meta("line");
    assert_eq!(line.namespaced_id, "cad.draw.line");
    assert_eq!(line.contexts, ["model", "paper"]);
    assert_eq!(meta("mspace").contexts, ["paper"]);
    assert_eq!(meta("pspace").contexts, ["paper"]);
    assert_eq!(meta("mview").contexts, ["paper"]);
    assert_eq!(meta("mview.polygonal").contexts, ["paper"]);
    assert_eq!(meta("vpclip").contexts, ["paper"]);
    assert_eq!(meta("viewport.set").contexts, ["model", "paper"]);
    assert_eq!(meta("vplayer").contexts, ["paper"]);
    assert_eq!(meta("plotwindow").contexts, ["model"]);
    for id in ["-vports", "vports", "vports.1", "vports.2", "vports.3", "vports.4"] {
        assert_eq!(meta(id).contexts, ["model", "paper"], "{id}");
    }
    assert_eq!(line.version, "1.0.0");
    assert_eq!(line.label_key, "Line");
    assert_eq!(status_on("xref", Target::Web), CommandStatus::Unsupported);
    assert_eq!(status_on("xref", Target::Desktop), CommandStatus::Available);
    assert_eq!(Target::current(), if cfg!(target_arch = "wasm32") { Target::Web } else { Target::Desktop });
    for id in MODEL_ONLY.iter().chain(PAPER_ONLY) {
        assert!(map.contains_key(id), "context table has unknown id `{id}`");
    }
    for meta in &reg {
        assert_eq!(meta.version, COMMAND_VERSION, "{}", meta.stable_id);
        assert_eq!(meta.label_key, meta.label, "{}", meta.stable_id);
        assert_eq!(meta.status, status_on(meta.stable_id, Target::current()), "{}", meta.stable_id);
        assert_eq!(status_on(meta.stable_id, Target::Desktop), CommandStatus::Available, "{}", meta.stable_id);
        let web = if XREF_IDS.contains(&meta.stable_id) { CommandStatus::Unsupported } else { CommandStatus::Available };
        assert_eq!(status_on(meta.stable_id, Target::Web), web, "{}", meta.stable_id);
    }
    assert_eq!(
        registry_json(line),
        json!({
            "id": "cad.draw.line", "commandId": "line", "version": "1.0.0", "labelKey": "Line", "defaultAliases": ["L", "LINE"],
            "contexts": ["model", "paper"], "capabilities": [], "undoable": true, "status": "available"
        })
    );
}

