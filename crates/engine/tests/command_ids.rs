fn schema_rows(value: &Value, path: &str, rows: &mut BTreeMap<String, String>) {
    match value {
        Value::Object(fields) if !fields.is_empty() => {
            rows.insert(path.to_string(), "object".to_string());
            for (key, value) in fields {
                schema_rows(value, &format!("{path}/{key}"), rows);
            }
        }
        Value::Array(items) if !items.is_empty() => {
            rows.insert(path.to_string(), "array".to_string());
            for (index, value) in items.iter().enumerate() {
                schema_rows(value, &format!("{path}/{index}"), rows);
            }
        }
        value => {
            rows.insert(path.to_string(), value.to_string());
        }
    }
}

fn assert_schema_type(value: &Value, schema: &Value, id: &str) {
    let valid = match schema["type"].as_str().expect("schema type") {
        "object" => value.is_object(),
        "string" => value.is_string(),
        "boolean" => value.is_boolean(),
        "array" => value.is_array(),
        kind => panic!("unhandled schema type `{kind}`"),
    };
    assert!(valid, "{id}: wrong type for {value} under {schema}");
    if let Some(variants) = schema.get("enum") {
        assert!(variants.as_array().expect("enum array").contains(value), "{id}: {value} is outside {variants}");
    }
    if let Some(constant) = schema.get("const") {
        assert_eq!(value, constant, "{id}: schema constant");
    }
    if let Some(minimum) = schema.get("minLength").and_then(Value::as_u64) {
        assert!(value.as_str().expect("string").chars().count() as u64 >= minimum, "{id}: string too short");
    }
    if let Some(items) = value.as_array() {
        if let Some(minimum) = schema.get("minItems").and_then(Value::as_u64) {
            assert!(items.len() as u64 >= minimum, "{id}: array too short");
        }
        if schema.get("uniqueItems") == Some(&Value::Bool(true)) {
            let unique: BTreeSet<String> = items.iter().map(Value::to_string).collect();
            assert_eq!(unique.len(), items.len(), "{id}: duplicate array entries");
        }
        for item in items {
            assert_schema_type(item, &schema["items"], id);
        }
    }
}

#[test]
fn command_schema_doc_is_current() {
    let schema = command_schema();
    let path = manifest_path("../../docs/workspace/command.schema.json");
    if updating() {
        let text = serde_json::to_string_pretty(&schema).expect("serialize command schema");
        fs::write(&path, format!("{text}\n")).expect("write command.schema.json");
    } else {
        let text = fs::read_to_string(&path).expect("read command.schema.json");
        let recorded: Value = serde_json::from_str(&text).expect("parse command.schema.json");
        let mut expected = BTreeMap::new();
        let mut found = BTreeMap::new();
        schema_rows(&schema, "", &mut expected);
        schema_rows(&recorded, "", &mut found);
        let differences = snapshot_differences(&expected, &found);
        assert!(differences.is_empty(), "command schema differs; run with UPDATE_COMMAND_IDS=1:\n{}", differences.join("\n"));
        assert_eq!(recorded, schema);
    }
    assert_eq!(schema["$schema"], "https://json-schema.org/draft/2020-12/schema");
    let required = schema["required"].as_array().expect("required array");
    let properties = schema["properties"].as_object().expect("schema properties");
    for meta in command_registry() {
        let entry = registry_json(&meta);
        assert_schema_type(&entry, &schema, meta.stable_id);
        let fields = entry.as_object().expect("entry object");
        for key in required {
            let key = key.as_str().expect("required key");
            assert!(fields.contains_key(key), "{}: missing required field `{key}`", meta.stable_id);
        }
        for (key, value) in fields {
            let field_schema = properties.get(key).unwrap_or_else(|| panic!("{}: additional property `{key}`", meta.stable_id));
            assert_schema_type(value, field_schema, meta.stable_id);
        }
    }
}
